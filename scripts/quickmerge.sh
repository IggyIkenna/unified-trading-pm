# STAGE 0.4: NOT-BEHIND GATE — quickmerge must not run from a STALE base
# The ONLY requirement is: local must NOT be BEHIND origin/<branch> (no unpulled
# remote commits). Having local commits / uncommitted changes that DEVIATE from
# origin is expected and fine — that's the work you're merging. So if behind, we
# pull the latest FIRST: fast-forward when possible, otherwise rebase your local
# commits on top of the latest. Block only if that rebase genuinely conflicts.
# Emergency override only: QUICKMERGE_ALLOW_BEHIND=1
#
# Extracted into a function (2026-07-22): STAGE 3's AGENT_MODE sentinel-invalid
# retry loop below re-invokes this SAME reconciliation before each regate retry,
# so a lost race against a concurrent peer push is retried automatically instead
# of forcing the calling agent to notice the failure and manually re-run
# quality-gates.sh + quickmerge.sh (quickmerge_sentinel_race_retry_storm_under_
# pm_doc_push_contention_2026_07_21: up to 27 consecutive full-QG losses
# observed in one session under heavy PM doc-push contention). Body unchanged
# from the original inline block — this is a pure extraction, not a behavior
# change, for the first (and only, on the common path) invocation.
# ============================================================================
_qm_stage_0_4_not_behind_gate() {
echo "=========================================="
echo "STAGE 0.4: Not-Behind Gate (pull latest first)"
echo "=========================================="
_QM_BRANCH=$(git branch --show-current 2>/dev/null || echo "")
if [ -z "$_QM_BRANCH" ]; then
  echo "[$REPO_NAME] detached HEAD — skipping not-behind gate"
else
  # Reconcile against the CONFIGURED UPSTREAM (@{u}), NOT origin/<branch-name>.
  # Slot worktrees on tab/<op>/<N> track origin/live-defi-rollout, while
  # origin/tab/<op>/<N> may be a stale snapshot — comparing against the latter
  # triggers a bogus 500+-commit rebase against a dead branch (incident 2026-06-03).
  _QM_UPSTREAM=$(git rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null || echo "")
  if [ -n "$_QM_UPSTREAM" ]; then
    _QM_REMOTE_REF="$_QM_UPSTREAM"
    _QM_REMOTE_NAME="${_QM_UPSTREAM%%/*}"
    _QM_REMOTE_BRANCH="${_QM_UPSTREAM#*/}"
  else
    _QM_REMOTE_REF="origin/$_QM_BRANCH"
    _QM_REMOTE_NAME="origin"
    _QM_REMOTE_BRANCH="$_QM_BRANCH"
  fi
  git fetch "$_QM_REMOTE_NAME" "$_QM_REMOTE_BRANCH" --quiet 2>/dev/null || true
  if ! git rev-parse "$_QM_REMOTE_REF" >/dev/null 2>&1; then
    echo "[$REPO_NAME] no $_QM_REMOTE_REF yet — skipping not-behind gate"
  else
    _QM_BEHIND=$(git rev-list "HEAD..$_QM_REMOTE_REF" --count 2>/dev/null || echo 0)
    _QM_AHEAD=$(git rev-list "$_QM_REMOTE_REF..HEAD" --count 2>/dev/null || echo 0)
    if [ "${_QM_BEHIND:-0}" = "0" ]; then
      echo "[$REPO_NAME] ✅ not behind $_QM_REMOTE_REF (ahead=$_QM_AHEAD; local deviations are fine) — proceeding"
    else
      echo "[$REPO_NAME] behind $_QM_REMOTE_REF by $_QM_BEHIND (ahead=$_QM_AHEAD) — pulling latest first..."
      # Keep git's OWN reason. Discarding it (the old `2>/dev/null`) is what turned the branch
      # below from a diagnosis into a guess: measured 2026-08-10, a run blocked with
      # "working-tree overlap" and a RECOVERY line telling the agent to `git stash push -- <file>`,
      # when the real cause was three unmerged index entries left by an earlier stash-apply. That
      # advice fixes nothing, and the whole quickmerge run was wasted before the agent worked out
      # that git had said something else entirely.
      # The `&& … || …` form is load-bearing: `set -e` is active here (line 89), and a bare
      # assignment whose command substitution fails would abort quickmerge outright. The old
      # `if git pull …; then` was safe only because a condition suppresses errexit.
      _QM_FF_ERR="$(git pull --ff-only "$_QM_REMOTE_NAME" "$_QM_REMOTE_BRANCH" --quiet 2>&1)" \
        && _QM_FF_RC=0 || _QM_FF_RC=$?
      if [ "$_QM_FF_RC" -eq 0 ]; then
        echo "[$REPO_NAME] ✅ fast-forwarded to latest — now current"
      elif printf '%s' "$_QM_FF_ERR" | grep -q 'unmerged files\|unresolved conflict'; then
        # A DIFFERENT condition with a DIFFERENT fix. The index still holds conflict stages from
        # an earlier interrupted merge/stash-apply; no amount of stashing a file by name helps.
        echo "QUICKMERGE_BLOCKED code=PRECOMMIT_UNMERGED_INDEX repo=${REPO_NAME} branch=${_QM_REMOTE_BRANCH} behind=${_QM_BEHIND} ahead=${_QM_AHEAD}"
        echo "RECOVERY: your index has unmerged entries from an earlier interrupted merge or stash-apply — git refuses to pull until they are resolved. Inspect with 'git ls-files -u', resolve the file's content (search it for <<<<<<< markers), 'git add' it by name, then re-run. Do NOT 'git checkout --theirs/--ours' a file you do not own."
        echo "[$REPO_NAME] ❌ BLOCKED: unmerged index entries — git said: ${_QM_FF_ERR%%$'\n'*}"
        exit 1
      elif [ "${_QM_AHEAD:-0}" = "0" ]; then
        echo "[$REPO_NAME]    git's own reason: ${_QM_FF_ERR%%$'\n'*}"
        # Pre-commit case (autostash_pop_restores_foreign_wip_into_the_index_2026_07_17.md,
        # decided fix 2026-08-01): ahead=0 means there is no local commit for `--rebase` to
        # replay, so ff-only's failure here can ONLY be a working-tree content OVERLAP (a
        # locally-dirty tracked file the incoming diff also touches) — not commit-graph
        # divergence. Skip the forced `--rebase --autostash` fallback for this case: it would
        # stash-and-repop that overlapping file (and any OTHER dirty foreign file in this shared
        # checkout) back into the working tree/index for zero reconciliation benefit — the exact
        # non-conflict happy-path hazard this doc measured. Report + block; git's own refusal
        # already named the overlapping file(s).
        _QM_CODE="PRECOMMIT_WORKING_TREE_CONFLICT"
        if [ "${QUICKMERGE_ALLOW_BEHIND:-}" = "1" ]; then
          echo "[$REPO_NAME] ⚠️  still $_QM_BEHIND behind (${_QM_CODE}) — QUICKMERGE_ALLOW_BEHIND=1, continuing"
        else
          echo "QUICKMERGE_BLOCKED code=${_QM_CODE} repo=${REPO_NAME} branch=${_QM_REMOTE_BRANCH} behind=${_QM_BEHIND} ahead=0"
          echo "RECOVERY: a dirty file in your working tree overlaps the incoming upstream diff (ahead=0 — not commit-graph divergence, so --rebase --autostash is not attempted here). Commit or 'git stash push -- <your-file>' YOUR file BY NAME, re-run the pull, then restore your stash. See autostash_pop_restores_foreign_wip_into_the_index_2026_07_17.md."
          echo "[$REPO_NAME] ❌ BLOCKED: $_QM_BEHIND behind $_QM_REMOTE_REF, ff-only refused (working-tree overlap, ahead=0)."
          echo "   Emergency override: QUICKMERGE_ALLOW_BEHIND=1 bash scripts/quickmerge.sh ..."
          exit 1
        fi
      elif git pull --rebase --autostash "$_QM_REMOTE_NAME" "$_QM_REMOTE_BRANCH" --quiet 2>/dev/null; then
        echo "[$REPO_NAME] ✅ rebased local commits onto latest — now current"
        # Post-commit case (autostash_pop_restores_foreign_wip_into_the_index_2026_07_17.md,
        # decided fix 2026-08-01): --autostash's pop restores EVERY file it stashed back into the
        # INDEX (staged) on pop — including foreign files owned by other agents dirty in this
        # shared checkout, not just this repo's own already-committed work. Unconditionally
        # unstage right here, BEFORE any of this script's own `git add` below: `git restore
        # --staged .` only touches the index (never working-tree content, so it cannot destroy
        # anything) and guarantees the index holds only what this run explicitly re-adds,
        # regardless of what the pop just restaged.
        git restore --staged . 2>/dev/null || true
      else
        # Structured error contract (265, 2026-06-17): emit a machine-parseable QUICKMERGE_BLOCKED
        # line so an agent self-serves recovery without an operator paste. Capture the conflicting
        # files BEFORE the abort, and distinguish the autostash-pop foot-gun from a plain rebase
        # conflict. `git rebase --abort` is SAFE (never overwrites; the autostash + peer commits
        # stay intact) and returns 0 IFF a rebase was actually in progress.
        _QM_CONFLICTS="$(git diff --name-only --diff-filter=U 2>/dev/null | tr '\n' ' ' | sed 's/ *$//')"
        if git rebase --abort 2>/dev/null; then
          _QM_CODE="BEHIND_DIVERGED_CONFLICT"   # rebase was mid-flight (now aborted; your autostash is pending in `git stash list`)
        else
          _QM_CODE="AUTOSTASH_POP_CONFLICT"     # no rebase in progress → the autostash pop conflicted; YOUR work is in `git stash list` — do NOT drop it
        fi
        if [ "${QUICKMERGE_ALLOW_BEHIND:-}" = "1" ]; then
          echo "[$REPO_NAME] ⚠️  still $_QM_BEHIND behind (${_QM_CODE}) — QUICKMERGE_ALLOW_BEHIND=1, continuing"
        else
          echo "QUICKMERGE_BLOCKED code=${_QM_CODE} repo=${REPO_NAME} branch=${_QM_REMOTE_BRANCH} behind=${_QM_BEHIND} ahead=${_QM_AHEAD} conflicts=\"${_QM_CONFLICTS}\""
          echo "RECOVERY: SUB_AGENT_MANDATORY_RULES.md § \"Quickmerge behind-remote\" — preserve peer commits, stash YOUR files BY NAME, git pull --rebase, reconcile essence, re-QG, re-quickmerge. NEVER 'git checkout HEAD -- <foreign-file>' then 'git stash drop' (destroys a peer's only WIP copy)."
          echo "[$REPO_NAME] ❌ BLOCKED: $_QM_BEHIND behind $_QM_REMOTE_REF, auto-rebase hit conflicts (code=${_QM_CODE})."
          echo "   Emergency override: QUICKMERGE_ALLOW_BEHIND=1 bash scripts/quickmerge.sh ..."
          exit 1
        fi
      fi
    fi
  fi
fi
}
