# quickmerge_stage5_push_loses_fast_forward_race_under_high_churn_2026_07_27: under sustained
# branch churn (commits landing every 20-90s), the remote can move again during the ~45-300s
# Pass-1 QG re-verification that already ran above — by the time we reach THIS push, it loses
# the non-fast-forward race. The content hasn't changed, only the base commit has, so retrying
# the whole pipeline (re-running the full QG suite) per collision is pure waste — measured at
# 16+ attempts / 70+ min for one non-conflicting change. Retry just the cheap rebase+push here,
# bounded, before ever asking the caller to re-invoke quickmerge. Also fixes a real pre-existing
# bug: the old bare `git push ... 2>/dev/null` never checked its own exit code, so a failed push
# silently fell through into PR creation as if it had succeeded.
_QM_PUSH_RETRIES="${QUICKMERGE_PUSH_RETRIES:-5}"
_qm_push_attempt=0
_qm_push_ok=0
while [ "$_qm_push_attempt" -lt "$_QM_PUSH_RETRIES" ]; do
  _qm_push_attempt=$((_qm_push_attempt + 1))
  # Heal evidence citations that a rebase invalidated -- INSIDE the loop, because the
  # push-retry path below rebases again and re-orphans whatever the previous pass fixed.
  # Same reconciler safe-doc-push uses; no-ops (one grep) when the staged files cite nothing.
  if [ -n "$FILES_ARG" ] && [ -f "$WORKSPACE_ROOT/unified-trading-pm/scripts/dev/reconcile-sha-citations.sh" ]; then
    # shellcheck source=/dev/null
    source "$WORKSPACE_ROOT/unified-trading-pm/scripts/dev/reconcile-sha-citations.sh" 2>/dev/null || true
    if declare -F reconcile_sha_citations >/dev/null 2>&1; then
      # shellcheck disable=SC2086  # intentional word-split: FILES_ARG is a space-separated path list
      RSC_CALLER_REPO="${QM_CALLER_REPO:-$(git rev-parse --show-toplevel 2>/dev/null)}" \
        reconcile_sha_citations "$BRANCH" $FILES_ARG || true
    fi
  fi
  # In isolation we are on a detached HEAD by design (see _qm_checkout_ship_branch), so there is
  # no local branch for `-u` to bind and `git push -u origin $BRANCH` would push the SHARED
  # clone's stale refs/heads/$BRANCH instead of the commit we just made. Push the explicit
  # refspec, exactly as safe-doc-push.sh does.
  if [ -n "${QM_IN_ISOLATION:-}" ]; then
    _qm_push_err=$(git push origin "HEAD:refs/heads/$BRANCH" --quiet 2>&1) && { _qm_push_ok=1; break; }
  else
    _qm_push_err=$(git push -u origin "$BRANCH" --quiet 2>&1) && { _qm_push_ok=1; break; }
  fi
  echo "[$REPO_NAME] ⚠️  push rejected (attempt $_qm_push_attempt/$_QM_PUSH_RETRIES) — rebasing onto the new remote tip and retrying (no QG re-run needed, content unchanged)..." >&2
  if ! git pull --rebase --autostash origin "$BRANCH" --quiet 2>/dev/null; then
    echo "[$REPO_NAME] ❌ rebase during push-retry hit a real conflict — resolve manually (git status)." >&2
    exit 1
  fi
done
if [ "$_qm_push_ok" != 1 ]; then
  echo "[$REPO_NAME] ❌ push to $BRANCH failed after $_qm_push_attempt attempts (non-fast-forward race under high churn). Last error: $_qm_push_err" >&2
  exit 1
fi

# Post-push ancestry gate (operator ruling 2026-08-06; SSOT:
# plans/active/issues/wip_preserve_refs_silently_unrecovered_2026_07_29.md [SCRIPT] P1).
# Re-fetch origin/$BRANCH and assert the just-pushed sha is still an ancestor.
# sha-ancestry is the right oracle HERE specifically — we pushed that exact sha a moment
# ago, so ancestry is exactly the claim being made. A warn-and-proceed is NOT acceptable:
# a false SHIPPED line is worse than a hard error (the originating incident went undetected
# because a stale log line survived a session-death boundary with no re-verification).
# Note: do NOT generalise this check to aged refs — see the issue doc § "Trap" for why
# sha-ancestry on an older ref will cry wolf (content may have been re-shipped under a
# different sha). Only use it here, at the instant after a push of that exact sha.
_QM_PUSHED_SHA=$(git rev-parse HEAD 2>/dev/null)
if ! git fetch origin "$BRANCH" --quiet 2>/dev/null; then
  echo "[$REPO_NAME] ❌ post-push fetch of origin/$BRANCH failed — cannot verify ancestry. Do NOT treat this as SHIPPED." >&2
  exit 1
fi
if ! git merge-base --is-ancestor "$_QM_PUSHED_SHA" "origin/$BRANCH" 2>/dev/null; then
  echo "[$REPO_NAME] ❌ POST-PUSH ANCESTRY CHECK FAILED: ${REPO_NAME}@${_QM_PUSHED_SHA:0:9} is not an ancestor of origin/$BRANCH after push returned success." >&2
  echo "[$REPO_NAME]    The remote branch was moved between the push and this verification (e.g. by a concurrent quarantine-reset)." >&2
  echo "[$REPO_NAME]    Commit is reachable locally — do NOT mark this run as SHIPPED. Investigate before retrying." >&2
  exit 1
fi
echo "[$REPO_NAME] ✅ post-push ancestry verified — ${_QM_PUSHED_SHA:0:9} is an ancestor of origin/$BRANCH"
# The SHA to put in the plan checkbox. Stated explicitly because the SHA a worker sees at
# `git commit` time is NOT the one that lands: every push here rebases first, which rewrites
# it. Citing the pre-rebase SHA is the single most common source of a FALSE
# check_plan_commit_sha_evidence.py failure on work that was genuinely done -- and it is
# silent on the authoring machine, where the orphaned object still resolves.
echo "[$REPO_NAME] 📌 CITE THIS in the plan checkbox: ${REPO_NAME}@${_QM_PUSHED_SHA:0:10}"
# Did this run's reconcile eat uncommitted work OUTSIDE --files? Advisory: the push already
# succeeded and must not be retroactively failed, but silence here is what made the original
