# RE-ASSERT --files SCOPE (same discipline as the pre-commit-modified-files retry below):
# a shared, non-isolated working tree can have OTHER agents' concurrent foreign dirty files
# at the exact moment quickmerge runs (observed 2026-07-09: --files pointed at already-
# committed paths, but an unrelated tree-wide `git status --porcelain` check saw foreign
# WIP and fell through to a doomed `git commit` with nothing staged, hard-failing the whole
# run). When --files is set, only THOSE paths need to be clean to conclude "already
# committed, safe to push" — the unscoped path is unaffected and still requires a fully
# clean tree (the caller owns the whole tree there).
# Re-stage helper (deletion-aware, --files-scoped when set) — shared by the
# reformat-retry below AND the branch-drift retry loop, so both retry paths
# re-stage identically instead of drifting into two slightly different rules.
_qm_restage_target_files() {
  if [ -n "$FILES_ARG" ]; then
    for f in $FILES_ARG; do
      if [ -e "$f" ]; then
        git add -- "$f"
      elif git ls-files --error-unmatch -- "$f" >/dev/null 2>&1; then
        # Deletion of a tracked path — see the STAGE-5 comment above for why this
        # is `git rm --cached` and not `git add` (gitignored paths make `git add`
        # exit 1 while still staging, which aborts the retry).
        git rm --cached --quiet -- "$f"
      fi
    done
  else
    git add -A
  fi
}

# _qm_locked_git_commit -- serialise `git commit` (which runs the prek/pre-commit hook chain
# synchronously) against any OTHER concurrent commit in this SAME checkout, in this or any
# other process (e.g. safe-doc-push.sh, which wraps its own commit calls the same way).
# prek_stash_restore_race_destroys_shared_checkout_wip_2026_08_08: prek stashes unstaged
# changes to a patch at hook-batch START and restores it at the END; two overlapping
# `git commit` calls in one checkout can interleave those windows, and the first session's
# restore silently reverts a second session's newer edit to HEAD -- no error, no conflict
# marker, no stash entry to recover from. A flock scoped to this checkout's .git dir closes
# the interleaving window without touching prek itself -- a distinct lock file/FD from the
# cascade lock above (different critical section, same degrade-to-unlocked convention).
# Held ONLY around the single `git commit` call, never across the retry loop below (up to
# _QM_COMMIT_RETRY_MAX attempts) -- each retry re-acquires+releases cleanly, no self-deadlock.
# _qm_unstage_foreign_paths -- in --files (scoped) mode, drop anything from the index that
# this run did not put there, immediately before committing.
#
# WHY: `--files` scopes what quickmerge STAGES, but the commit itself is bare `git commit`,
# which commits the whole index. In a shared checkout a peer session that stages between our
# `git add` and our commit has its files absorbed into OUR commit, under OUR message and
# authorship. Measured 2026-08-10 in agent-orchestrator, BOTH directions in one session:
# a peer's bare commit swallowed this session's three staged source files (shipping a fix to
# origin inside a commit titled "docs(context): record DeepSeek's measured ... ceiling", with
# its tests left behind), and later a quickmerge run named two files yet pushed a commit
# containing NEITHER -- only a peer's untracked test file. Both reported success and verified
# push ancestry, so neither was visible without reading the commit afterwards.
#
# Deliberately NOT a pathspec commit (`git commit -- <files>`), which looks like the obvious
# fix and is wrong here: a pathspec commit takes the WORKING TREE state for those paths, so a
# path staged as `git rm --cached` while still present on disk -- the untrack-in-the-same-
# commit shape the STAGE-5 staging loop handles explicitly -- would be silently re-added.
# Unstaging the extras instead preserves every index semantic the staging loop established.
#
# The allowed set is the caller's --files PLUS the two paths this script stages itself for
# their mode bits (see the chmod loop above). Unscoped runs are untouched: there the caller
# owns the whole tree by definition (`git add -A`).
_qm_unstage_foreign_paths() {
  [ -z "$FILES_ARG" ] && return 0
  local allowed=" $FILES_ARG scripts/quickmerge.sh scripts/quality-gates.sh "
  local staged p
  staged="$(git diff --cached --name-only 2>/dev/null || true)"
  [ -z "$staged" ] && return 0
  while IFS= read -r p; do
    [ -z "$p" ] && continue
    case "$allowed" in
      *" $p "*) continue ;;
    esac
    echo "[$REPO_NAME] ⚠️  unstaging foreign path — staged by another session, not in --files: $p"
    git restore --staged -- "$p" 2>/dev/null || git reset -q HEAD -- "$p" 2>/dev/null || true
  done <<EOF
$staged
EOF
}

_qm_locked_git_commit() {
  local lock_fd=222 lock_file rc
  lock_file="$(git rev-parse --git-dir 2>/dev/null)/quickmerge-commit.lock"
  # Scope the index to THIS run's files before every commit attempt (incl. retries and the
  # amend path) -- inside the flock below would be better still, but the lock is acquired
  # per-branch just below and this keeps one call site for all of them.
  _qm_unstage_foreign_paths
  # pm_repo_commit_rate_exceeds_precommit_hook_duration_2026_08_10 (P0): the pre-commit drift
  # gate is ADVISORY for quickmerge's own commit -- STAGE 0.4 already reconciles against origin
  # and the push path re-reconciles on rejection, so "your commit sits on current origin" is
  # enforced AFTER the commit, where it costs seconds instead of re-paying a 118s hook chain.
  # Measured 2026-08-10 in unified-trading-pm: hook chain 118s vs 60-80s commit inter-arrival,
  # so the gate fired on essentially every attempt. Scoped to this call and unset right after,
  # so it never leaks; a bare human `git commit` keeps the hard block.
  export DRIFT_GATE_ADVISORY=1
  # push-host-governor.sh (2026-08-09): host-wide validation-phase token (K=8 default) around
  # the hook-chain-running commit call itself, nested OUTSIDE this pre-existing per-checkout
  # flock (that one only prevents the prek-stash-restore race WITHIN one checkout; this one
  # bounds how many checkouts host-wide run prek's synchronous hook chain at once).
  push_gov_acquire_validate
  if [ -z "$lock_file" ] || [ "$lock_file" = "/quickmerge-commit.lock" ]; then
    git commit "$@"
    rc=$?
    unset DRIFT_GATE_ADVISORY
    push_gov_release_validate
    return "$rc"
  fi
  if command -v flock >/dev/null 2>&1 && eval "exec ${lock_fd}>\"\$lock_file\"" 2>/dev/null; then
    flock "$lock_fd"
    git commit "$@"
    rc=$?
    flock -u "$lock_fd" 2>/dev/null || true
    eval "exec ${lock_fd}>&-" 2>/dev/null || true
    unset DRIFT_GATE_ADVISORY
    push_gov_release_validate
    return "$rc"
  fi
  git commit "$@"
  rc=$?
  unset DRIFT_GATE_ADVISORY
  push_gov_release_validate
  return "$rc"
}

# Bounded retry for a commit-time branch-drift race (ao_quickmerge_stage5_
# branch_drift_retry_2026_07_27): STAGE 0.4 already pulled us current before QG
# ran, but on a busy shared branch a peer can push AGAIN in the seconds between
# that pull and this commit, so the check-branch-drift pre-commit hook fails
# here — previously a hard, uninformative exit requiring the calling agent to
# manually pull + re-stage + re-invoke quickmerge from scratch (observed: 20+
# consecutive manual retries in one session under heavy live-defi-rollout
# traffic, each burning a full quickmerge re-run). This is a pure GIT-REF race,
# not a content/QG-validity race (contrast the sentinel retry above, which
# re-gates because the TREE may have changed) — our staged --files paths were
# already Pass-1-QG-verified, and a peer's commit landing on unrelated files
# doesn't invalidate that, so recovery here is just "pull, re-stage, recommit",
# never a re-gate. _qm_stage_0_4_not_behind_gate is reused verbatim (same
# ff-only-then-rebase-autostash-then-QUICKMERGE_BLOCKED contract already
# trusted elsewhere in this script) so a GENUINE same-file conflict still hard-
# blocks with the structured error instead of this loop papering over it.
#
# prek_patch_cache_replays_stale_diff_onto_unrelated_files_2026_07_29: the commit-hook
# chain (prek) has been observed leaving UNRELATED tracked files (outside --files scope)
# dirty with corrupted content after a successful commit — e.g. a garbled repeated-date
# `last_updated:` runaway string, a silently-deleted `author:` line — reproduced twice
# byte-identical in one session. `_qm_restage_target_files` above already stops that
# corruption from being STAGED into the commit (scoped re-stage, never `git add -A`), but
# nothing previously stopped it from lingering DIRTY in the working tree afterward, where
# it rides along invisibly until some later `git status` catches it (or worse, a future
# `git add -A` slip commits it). Snapshot the unstaged-diff paths BEFORE any hook runs so
# we can tell, after the commit, exactly which paths the hook chain newly dirtied — a path
# that was clean pre-hook and dirty post-hook is proven hook side-effect noise, not
# pre-existing foreign WIP (which we must never touch per the multi-agent safety rule), so
# it is safe to auto-revert.
_QM_PRE_HOOK_UNSTAGED="$(git diff --name-only 2>/dev/null || true)"

# prek_stash_restore_race_destroys_shared_checkout_wip_2026_08_08 (todo 3, "make the loss
# loud"): the flock in _qm_locked_git_commit closes the interleaving window for commits made
# THROUGH this script/safe-doc-push.sh, but it can't cover a `git commit` invoked some other
# way in this same checkout (a manual dev commit, a future call site). Checksum every
# already-unstaged file BEFORE the commit call — exactly the set prek's own stash captures —
# so a silent revert (the stash/restore race reinstating a stale snapshot over a newer edit)
# is DETECTABLE even when the lock didn't prevent it, instead of reporting a clean tree.
_QM_PRE_HOOK_CHECKSUMS=""
if [ -n "$_QM_PRE_HOOK_UNSTAGED" ]; then
  while IFS= read -r _qm_snap_path; do
    [ -z "$_qm_snap_path" ] && continue
    [ -f "$_qm_snap_path" ] || continue
    _QM_PRE_HOOK_CHECKSUMS="${_QM_PRE_HOOK_CHECKSUMS}${_qm_snap_path}	$(git hash-object -- "$_qm_snap_path" 2>/dev/null)
"
  done <<EOF
$_QM_PRE_HOOK_UNSTAGED
EOF
fi

# push-host-governor.sh (2026-08-09): from here through the post-push ancestry check below is
# the actual git-remote critical section (commit-retry's own fetch+rebase reconciliation, then
# push-retry's own fetch+rebase+push) -- everything ABOVE this point (STAGE 0-5, the Pass-1 QG
# re-verification) stays UNGATED and runs with real cross-slot concurrency, exactly per the
# operator-agreed split: only the part that actually collides on GitHub's single-writer ref
# gets serialised. Released once, on the success path after ancestry verification; every exit 1
# between here and there auto-releases via the OS closing the FD on process death (see the
# governor file's own header) so a failure never leaves the next queued slot waiting forever.
push_gov_acquire_push "$REPO_NAME" "$BRANCH"

_QM_FRESH_COMMIT=0
_QM_COMMIT_RETRY_MAX=15
_QM_COMMIT_ATTEMPT=0
while true; do
  _QM_ALREADY_COMMITTED=0
  if [ -z "$(git diff --cached --name-only)" ]; then
    if [ -n "$FILES_ARG" ]; then
      # shellcheck disable=SC2086  # intentional word-split: FILES_ARG is a space-separated path list
      [ -z "$(git status --porcelain -- $FILES_ARG)" ] && _QM_ALREADY_COMMITTED=1
    elif [ -z "$(git status --porcelain)" ]; then
      _QM_ALREADY_COMMITTED=1
    fi
  fi

  if [ "$_QM_ALREADY_COMMITTED" = 1 ]; then
    # Nothing staged and (--files paths | whole tree) clean — changes were already committed
    # in a previous quickmerge run (or by a worker that commits before calling quickmerge, per
    # the documented --agent flow). That pre-existing commit never passed through the trailer
    # stamp above, so check_strict_quickmerge.py/scripts/hooks/pre-push will reject the
    # push unless HEAD already carries a Quickmerge: trailer — amend it on now if missing.
    if git log -1 --format=%B | grep -q '^Quickmerge:'; then
      echo "[$REPO_NAME] ℹ️  Working tree clean (scoped to --files, if set) — changes already committed. Proceeding to push."
    else
      _QM_AMEND_MSG_FILE=$(mktemp "${TMPDIR:-/tmp}/qm-amend-msg.XXXXXX")
      { git log -1 --format=%B; printf '\nQuickmerge: %s\n' "$_QM_TRAILER_KIND"; } >"$_QM_AMEND_MSG_FILE"
      _qm_locked_git_commit --amend -F "$_QM_AMEND_MSG_FILE" --quiet
      rm -f "$_QM_AMEND_MSG_FILE"
      echo "[$REPO_NAME] ℹ️  Working tree clean — changes already committed but missing the Quickmerge trailer; amended HEAD to add 'Quickmerge: ${_QM_TRAILER_KIND}'. Proceeding to push."
    fi
    break
  fi

  if _qm_locked_git_commit -m "$_QM_COMMIT_MSG" --quiet; then
    _QM_FRESH_COMMIT=1
    break
  fi

  # Pre-commit may have modified files (e.g. Prettier). Re-stage and retry once.
  # RE-ASSERT --files SCOPE: a hook that reformats files must NOT let `git add -A`
  # sweep FOREIGN modified files (another agent's WIP, an inventory regen, a concurrent
  # edit) into a scoped commit — that is the prek-auto-stage-vs-`--files` foot-gun. When
  # --files is set, re-stage ONLY those paths (the hook's edits to YOUR files re-stage;
  # foreign modified files stay out of the index). Only the unscoped path uses `git add -A`.
  _qm_restage_target_files
  if _qm_locked_git_commit -m "$_QM_COMMIT_MSG" --quiet; then
    _QM_FRESH_COMMIT=1
    if [ -n "$FILES_ARG" ]; then
      echo "[$REPO_NAME] Pre-commit modified files; re-staged (scoped to --files) and committed on retry" >&2
    else
      echo "[$REPO_NAME] Pre-commit modified files; staged and committed on retry" >&2
    fi
    break
  fi

  # Still failing after the reformat-retry. Distinguish a branch-drift RACE
  # (retryable — pull and try again) from a genuine content-level pre-commit
  # failure (lint/type/etc — pulling can never fix this, so fail fast, never
  # loop blindly).
  _QM_DRIFT_UPSTREAM=$(git rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null || echo "")
  if [ -n "$_QM_DRIFT_UPSTREAM" ]; then
    git fetch "${_QM_DRIFT_UPSTREAM%%/*}" --quiet 2>/dev/null || true
    _QM_STILL_BEHIND=$(git rev-list "HEAD..$_QM_DRIFT_UPSTREAM" --count 2>/dev/null || echo 0)
  else
    _QM_STILL_BEHIND=0
  fi
  if [ "${_QM_STILL_BEHIND:-0}" = "0" ]; then
    echo "[$REPO_NAME] ❌ Commit failed (pre-commit may have failed). Run: pre-commit run --all-files; git add -A; git commit -m \"...\"" >&2
    exit 1
  fi

  _QM_COMMIT_ATTEMPT=$((_QM_COMMIT_ATTEMPT + 1))
  if [ "$_QM_COMMIT_ATTEMPT" -gt "$_QM_COMMIT_RETRY_MAX" ]; then
    echo "[$REPO_NAME] ❌ Commit still losing the branch-drift race after ${_QM_COMMIT_RETRY_MAX} retries — sustained" >&2
    echo "  contention, not a one-off. Run: git pull --ff-only ; git add <your files> ; retry quickmerge.sh" >&2
    exit 1
  fi
  _QM_COMMIT_BACKOFF=$((1 + RANDOM % 3))
  echo "[$REPO_NAME] ⏳ commit lost the branch-drift race (peer pushed mid-commit, behind=${_QM_STILL_BEHIND}) — retry ${_QM_COMMIT_ATTEMPT}/${_QM_COMMIT_RETRY_MAX} in ${_QM_COMMIT_BACKOFF}s"
  sleep "$_QM_COMMIT_BACKOFF"
  _qm_stage_0_4_not_behind_gate
  _qm_restage_target_files
done

