if [ -f "scripts/quality-gates.sh" ]; then
  if [ "$AGENT_MODE" = true ]; then
    # ── AGENT FAST-PATH: verify Pass 1 sentinel instead of re-running QG ──
    # Rec #1 (qg_sentinel_content_hash_and_slicing): the sentinel records the COMMIT SHA
    # at Pass-1 QG time. A bare SHA==HEAD check loses the race vs concurrent LDR writers —
    # an UNRELATED fast-forward (CI machinery / peer agents) advances HEAD and stales a
    # still-valid green QG, even though nothing in the files being shipped changed.
    # Content fallback: if HEAD only FAST-FORWARDED past the sentinel commit and the TREE is
    # byte-identical between them, the Pass-1 QG still covers exactly what is being pushed →
    # accept (re-verify by content, not by parent commit).
    #
    # TREE-scoped, NOT --files-scoped (2026-07-18). This check used to diff only `-- $FILES_ARG`,
    # i.e. "the files I am shipping have not changed since my green QG". That does NOT imply the
    # TREE passes QG, and quickmerge pushes the WHOLE TREE. Typecheck/test gates are WHOLE-PROGRAM:
    # a peer's edit to file A breaks file B that I never listed. Measured on deployment-ui
    # 2026-07-18: e643a5c changed `getUpcomingFixtures` to return `UpcomingFixturesResult` in
    # src/api/client.ts (touching only client.ts + LifecycleCards* + mock-api.ts) and broke
    # src/components/UpcomingFixtures.tsx + .test.tsx — files that commit NEVER TOUCHED. The
    # --files sentinel was satisfied, Pass 2 was skipped, and a tsc-red tree landed on LDR
    # (ci-status: deployment-ui SIT_VALIDATED → FAILING). Dozens of foreign files had changed
    # between that sentinel and HEAD, none of them QG-verified.
    #
    # Safety now: sentinel must be an ANCESTOR of HEAD (forward-only; rejects divergence/rewind)
    # AND the full tree must be unchanged. The fast-path therefore still covers the case the
    # content fallback was written for — a HEAD advance that changes NOTHING (an empty commit, a
    # no-op merge/backmerge, a revert-and-reapply) — but any real content movement, by me or a
    # peer, now correctly forces a Pass-2 QG re-run. On a busy shared branch that means more
    # re-runs; that is the honest cost of "what you push is what QG validated".
    # Sentinel check factored into a function returning 0 (valid — proceed) or 1
    # (invalid) WITHOUT exiting, so the bounded retry loop below can act on a lost
    # race instead of the script dying on the first attempt (2026-07-22:
    # quickmerge_agent_sentinel_race_vs_own_rebase_2026_07_16 /
    # quickmerge_sentinel_invalidated_by_its_own_autopull_2026_07_18 /
    # quickmerge_sentinel_race_retry_storm_under_pm_doc_push_contention_2026_07_21
    # — all three converge on "the sentinel logic is CORRECT (tree-strict, kept
    # exactly as-is — do NOT weaken ancestry/scope), the defect is throughput: a
    # lost race just hard-fails instead of automatically re-gating the now-current
    # tree and retrying", up to 27 consecutive full-QG losses observed on one
    # session under heavy PM doc-push contention). Sets _SENTINEL_SHA/_CURRENT_SHA
    # as a side effect for the caller's error message on final failure.
    _qm_check_agent_sentinel() {
      _SENTINEL=".qg_last_passed_sha"
      _CURRENT_SHA=$(git rev-parse HEAD 2>/dev/null || echo "")
      _SENTINEL_SHA=""
      # Line 1 = the SHA (unchanged contract); lines 2+ = the ENVIRONMENT/DEPLOYMENT_ENV
      # config the sentinel was written under (qg_sentinel_environment_blind_2026_07_23.md
      # item 2 — see base-service.sh's sentinel-write block for the writer side). `head -n1`
      # rather than the old whole-file `tr -d '[:space:]'` so multi-line sentinels parse
      # correctly; an OLD single-line (bare-SHA, pre-fix) sentinel still parses identically.
      [ -f "$_SENTINEL" ] && _SENTINEL_SHA=$(head -n1 "$_SENTINEL" 2>/dev/null | tr -d '[:space:]')
      if [ -z "$_SENTINEL_SHA" ]; then
        echo "[$REPO_NAME] ❌ Pass 1 quality-gates.sh sentinel missing — run: bash scripts/quality-gates.sh"
        return 1
      fi
      # Configuration binding: a sentinel verified under a DIFFERENT ENVIRONMENT/
      # DEPLOYMENT_ENV than THIS run resolved cannot certify this run's configuration —
      # e.g. a `quality-gates.sh --no-fix` re-run under the ambient prod default must not
      # satisfy a quickmerge run that will actually ship as ENVIRONMENT=development. An
      # OLD sentinel (written before this fix shipped — no config lines at all) has no
      # match and is treated as a mismatch: fails closed, forcing exactly one re-gate
      # under the new contract rather than silently trusting stale state. The
      # <absent> marker (rather than comparing against "") distinguishes
      # "no ENVIRONMENT= line at all" (old sentinel) from "line present with an empty
      # value" — a real ENVIRONMENT/DEPLOYMENT_ENV value can never legitimately equal it.
      if _SENTINEL_ENV_LINE=$(grep -m1 '^ENVIRONMENT=' "$_SENTINEL" 2>/dev/null); then
        _SENTINEL_ENV="${_SENTINEL_ENV_LINE#ENVIRONMENT=}"
      else
        _SENTINEL_ENV="<absent>"
      fi
      if _SENTINEL_DEPLOYMENT_ENV_LINE=$(grep -m1 '^DEPLOYMENT_ENV=' "$_SENTINEL" 2>/dev/null); then
        _SENTINEL_DEPLOYMENT_ENV="${_SENTINEL_DEPLOYMENT_ENV_LINE#DEPLOYMENT_ENV=}"
      else
        _SENTINEL_DEPLOYMENT_ENV="<absent>"
      fi
      if [ "$_SENTINEL_ENV" != "${ENVIRONMENT:-}" ] || [ "$_SENTINEL_DEPLOYMENT_ENV" != "${DEPLOYMENT_ENV:-}" ]; then
        echo "[$REPO_NAME] ❌ Pass 1 sentinel config mismatch — sentinel verified under ENVIRONMENT=${_SENTINEL_ENV:-<unset>}/DEPLOYMENT_ENV=${_SENTINEL_DEPLOYMENT_ENV:-<unset>}, this run resolved ENVIRONMENT=${ENVIRONMENT:-<unset>}/DEPLOYMENT_ENV=${DEPLOYMENT_ENV:-<unset>}. Re-run: bash scripts/quality-gates.sh"
        return 1
      fi
      if [ "$_SENTINEL_SHA" = "$_CURRENT_SHA" ]; then
        echo "[$REPO_NAME] ✅ SHA sentinel verified — skipping Pass 2 QG re-runs (already verified in Pass 1)"
        return 0
      elif git cat-file -e "${_SENTINEL_SHA}^{commit}" 2>/dev/null \
           && git merge-base --is-ancestor "$_SENTINEL_SHA" "$_CURRENT_SHA" 2>/dev/null \
           && git diff --quiet "$_SENTINEL_SHA" "$_CURRENT_SHA" 2>/dev/null; then
        echo "[$REPO_NAME] ✅ CONTENT sentinel verified — HEAD fast-forwarded ${_SENTINEL_SHA:0:9}→${_CURRENT_SHA:0:9} but the TREE is byte-identical between them (empty/no-op commit), so Pass-1 QG covers exactly what is being pushed. Skipping Pass 2 QG re-runs."
        return 0
      fi
      return 1
    }

    # Bounded retry with backoff+jitter (Option 2, decided 2026-07-19 in
    # quickmerge_sentinel_invalidated_by_its_own_autopull_2026_07_18; refined by
    # quickmerge_sentinel_race_retry_storm_under_pm_doc_push_contention_2026_07_21's
    # fix-2). On a lost race (sentinel invalid because a peer pushed between your
    # gate run and this check), automatically re-pull + re-gate + re-check instead
    # of dumping the retry onto the calling agent. The sentinel/ancestry logic
    # itself is UNCHANGED — this only automates the exact manual recipe an agent
    # would otherwise run by hand (do NOT relax tree-strictness; that was
    # explicitly rejected by the operator: typecheck/pytest are whole-program, a
    # peer's edit to an unrelated file can break one you never touched).
    _QM_SENTINEL_RETRY_MAX=3
    _QM_SENTINEL_ATTEMPT=0
    until _qm_check_agent_sentinel; do
      _QM_SENTINEL_ATTEMPT=$((_QM_SENTINEL_ATTEMPT + 1))
      if [ "$_QM_SENTINEL_ATTEMPT" -gt "$_QM_SENTINEL_RETRY_MAX" ]; then
        echo "[$REPO_NAME] ❌ Pass 1 quality-gates.sh sentinel invalid for current state."
        echo "  Sentinel: ${_SENTINEL_SHA:-<missing>}  HEAD: ${_CURRENT_SHA}"
        echo "  (The TREE changed since the sentinel — or the sentinel is not an ancestor of HEAD.)"
        echo "  Retried regate ${_QM_SENTINEL_RETRY_MAX}x against a moving HEAD and still lost the race —"
        echo "  this is sustained contention, not a one-off (see"
        echo "  quickmerge_sentinel_race_retry_storm_under_pm_doc_push_contention_2026_07_21)."
        # Name what moved. A whole-program gate (tsc/pytest) can break on a file you never touched,
        # so "but I didn't edit that" is not a reason to skip — show the evidence.
        _QM_TREE_DELTA=$(git diff --name-only "$_SENTINEL_SHA" "$_CURRENT_SHA" 2>/dev/null | head -8)
        if [ -n "$_QM_TREE_DELTA" ]; then
          _QM_DELTA_N=$(git diff --name-only "$_SENTINEL_SHA" "$_CURRENT_SHA" 2>/dev/null | wc -l | tr -d ' ')
          echo "  Changed since the sentinel (${_QM_DELTA_N} file(s), first 8):"
          printf '    %s\n' $_QM_TREE_DELTA
          echo "  NOTE: typecheck/tests are WHOLE-PROGRAM — a peer's edit can break a file you never"
          echo "        touched, so these must be re-validated together even if none are yours."
        fi
        echo "  Run: bash scripts/quality-gates.sh"
        exit 1
      fi
      _QM_BACKOFF=$((2 + RANDOM % 4 + _QM_SENTINEL_ATTEMPT * 3))
      echo "[$REPO_NAME] ⏳ sentinel invalid (HEAD moved — a peer likely pushed) — retry ${_QM_SENTINEL_ATTEMPT}/${_QM_SENTINEL_RETRY_MAX} in ${_QM_BACKOFF}s"
      sleep "$_QM_BACKOFF"
      _qm_stage_0_4_not_behind_gate
      echo "[$REPO_NAME] re-gating (regenerating the Pass-1 sentinel for the current tree)..."
      # Capture the re-gate's OWN output instead of inferring from its exit code. Discarding it
      # is how this branch came to assert "a REAL failure" for a run whose only ❌ was the
      # wall-clock budget: measured 2026-08-10, 602s billable against a 600s cap under 11
      # concurrent quickmerges, with every content check green. Telling an agent to go fix
      # content that was never broken costs a full extra gate and worsens the contention that
      # caused it. Same shape as the ff-only branch that blamed "working-tree overlap" for
      # unmerged index entries -- a confident verdict its evidence did not support.
      _qm_regate_log="${TMPDIR:-/tmp}/qm-regate-$$-${_QM_SENTINEL_ATTEMPT}.log"
      _qm_regate_rc=0
      { bash scripts/quality-gates.sh --no-fix $SKIP_CODEX 2>&1 | tee "$_qm_regate_log"; _qm_regate_rc=${PIPESTATUS[0]}; } || _qm_regate_rc=$?
      if [ "$_qm_regate_rc" -ne 0 ]; then
        # ❌ lines that are NOT the duration budget. Zero of them => no CONTENT check failed, so
        # this is a load verdict and must not be reported as a content one.
        # Count EVERY failure vocabulary, not just ❌. Measured 2026-08-10, on this guard's first
        # real failure: pytest emits `FAILED tests/...` with no ❌ at all, so a genuine test
        # failure counted as zero and the run told the agent "every content check passed. Do NOT
        # go looking for a content bug" while one was staring at it. A false all-clear is worse
        # than the false alarm this branch was written to remove.
        _qm_other_fail=$(sed 's/\x1b\[[0-9;]*m//g' "$_qm_regate_log" 2>/dev/null \
          | grep -E '❌|^FAILED |^ERROR |^E   ' | grep -vc 'must complete in <' || true)
        if [ "${_qm_other_fail:-1}" -eq 0 ]; then
          echo "[$REPO_NAME] ⏳ Re-gate hit ONLY the duration budget — every content check passed."
          echo "[$REPO_NAME]    This is HOST CONTENTION, not your change. Do NOT go looking for a content bug."
          echo "[$REPO_NAME]    Re-run when the host is quieter, or with IGNORE_TIMEOUT=true if the content"
          echo "[$REPO_NAME]    already gated green (codex/06-coding-standards/quality-gates.md)."
          exit 1
        fi
        echo "[$REPO_NAME] ❌ Re-gate FAILED against the current tree — this is a REAL failure, not a lost race."
        sed 's/\x1b\[[0-9;]*m//g' "$_qm_regate_log" 2>/dev/null | grep '❌' | grep -v 'must complete in <' | head -5 | sed 's/^/[re-gate] /'
        exit 1
      fi
    done
  else
    # Phase 1: lint auto-fix only (fast — ruff/eslint --fix, no tests/typecheck/build)
    echo "[$REPO_NAME] Phase 1: lint auto-fix..."
    bash scripts/quality-gates.sh --lint --fix $SKIP_CODEX

