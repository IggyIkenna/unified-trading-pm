# Single source of truth for all repos. Copy to scripts/quickmerge.sh.
#
# Three-tier branch model:
#   feat/*    → QG only, no PR (feature iteration, auto-detected)
#   staging   → ALL human commits converge here first; semver-agent validates label vs API diff;
#               SIT validates before promoting to main
#   main      → always stable; only updated via staging→main promotion or [skip ci] automation
#
# Routing model (staging-first):
#   All human commits → staging → semver-agent validates → SIT → main
#   [skip ci] automation commits (chore(release):, chore(manifest):, chore(deps):) → direct to main
#   --to-staging is now a no-op (kept for backwards compat; everything already routes to staging)
#   --hotfix enables abbreviated SIT (<2 min); use for production incidents only
#
# Usage:
#   ./scripts/quickmerge.sh "commit message"
#   ./scripts/quickmerge.sh "commit message" --files "path1 path2 path3"
#   ./scripts/quickmerge.sh "commit message" --dep-branch "my-feature"  # human-only; overrides manifest branch
#   ./scripts/quickmerge.sh "commit message" --to-staging               # no-op; kept for backwards compat
#   ./scripts/quickmerge.sh "commit message" --hotfix                   # abbreviated SIT on staging
#
# Branch resolution (no --dep-branch):
#   1. Read active_feature_branch from unified-trading-pm/workspace-manifest.json
#   2. Fallback to auto/YYYYMMDD-HHMMSS-$$ if manifest has no entry
#   Currently: active_feature_branch = live-defi-rollout (set in manifest)
#   ./scripts/quickmerge.sh "commit message" --quick
#
# Flags:
#   --files "p1 p2"    Stage only these paths (multi-agent: avoid committing other agents' work)
#   --dep-branch NAME  HUMAN-ONLY. Branch isolation when deps have uncommitted changes that aren't yet
#                      on main. Agents MUST NOT use this — they use active_feature_branch from manifest.
#   --to-staging       No-op (kept for backwards compat). All human commits now route to staging by default.
#   --hotfix           Routes to staging with abbreviated SIT (<2 min). Use for production incidents only.
#                      Agent still validates semver label. Adds 'hotfix' label to the staging PR.
#                      Requires a [hotfix] marker in the commit message (auditable break-glass).
#   --hotfix-to-main   Break-glass: land on LDR AND fast-track JUST this commit to main (cherry-pick onto a
#                      dedicated branch off main → PR → main; v2-on-main is the only gate; no trunk promote,
#                      no protection bypass). Requires a [hotfix-main] marker AND operator env
#                      QUICKMERGE_HOTFIX_TO_MAIN_OK=1 (agents cannot self-authorize the live path).
#   --quick            Skip only act simulation (Stage 4); all other checks run
#   (--skip-tests / --skip-typecheck / --skip-codex are REMOVED — WS-L #1014: the full QG is
#    mandatory before every push; quickmerge always runs lint+format+typecheck+TESTS+codex.)
#   --skip-preflight   Skip pre-flight audit (Stage 2 — a multi-agent SAFETY check, NOT a QG gate).
#                      Human/agent multi-agent use; does not weaken the quality gate.
#   --skip-dep-tier-gate Skip dep-tier-readiness check (Stage 1.7). HUMAN-ONLY — agents must NOT use this.
#   --build            OPT-IN LDR image build. Stamps a `Build-LDR: true` commit trailer; the cloud-native
#                      LDR build trigger (AWS CodeBuild webhook COMMIT_MESSAGE filter) fires the LDR image
#                      only when set. Default OFF (saves cost; removes red CodeBuild noise on drain PRs).
#                      The always-on MAIN build (deploy gate) is unaffected. SSOT:
#                      plans/active/issues/ci_pipeline_self_healing_gaps_2026_06_11.md § Gap 5.
#                      Use only when manually force-promoting out-of-order (e.g. hotfix on L0 lib while L1 is
#                      below staging). Prints a loud warning. Never combine with --agent.
#   --user-approved    Deprecated — Stage 0.3 is advisory-only; no gate to bypass.
#                      Version bumps are GHA-only (semver-agent.yml). Kept for backwards compat.
#
# [skip ci] automation commits:
#   Commits containing [skip ci] in the message bypass staging and go directly to main.
#   This preserves the automation path for: chore(release):, chore(manifest):, chore(deps):
#   These are generated by GHA automation and do not need semver-agent validation.
#
# Pipeline:
#   1. Dependency validation (workspace-manifest.json)
#   1.5. PM: dependency alignment check; ALL: staging lock check
#   1.6. Dependency version gate (deps semver-behind staging)
#   1.7. Dependency tier-readiness gate (deps ci_status must be STAGING_GREEN+ for LDR→staging promote)
#   2. Pre-flight audit (skippable with --skip-preflight for multi-agent use)
#   3. Local quality gates (two-phase: auto-fix → verify)
#   4. Act simulation (default; skip with --quick)
#   5. Create PR + enable auto-merge (base: staging for human commits; main for [skip ci] automation)
#
# Prerequisites:
#   - gh CLI installed and authenticated (gh auth login)
#   - Auto-merge enabled on the repo (Settings > General > Allow auto-merge)
#
# Notes:
#   - If quickmerge fails and you fix it: run quickmerge again. Do NOT
#     run quality gates first — quickmerge already runs quality gates.
#   - Agent sessions MUST use --files with the list of changed files to avoid
